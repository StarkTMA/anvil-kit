"""The wood sets' TypeScript. Each `*_ts()` function returns a file's text, and
`write_typescript()` writes into the project the scripts whose `ns:wood_set_<name>` custom
component is on a created block, so a block only has to use a component to get its script;
boats get the boat script. `index.ts` registers the scripts of every wood set created so
far, so creating a second set doesn't drop the first one's."""

from collections.abc import Iterable
from pathlib import Path

from anvil.api.actors.entity import Entity
from anvil.api.blocks.blocks import Block
from anvil.api.core.core import CONFIG

__all__ = ["constants_ts", "index_ts", "script_ts", "write_typescript"]

OUTPUT_DIRECTORY = "scripts/javascript/blocks/wood_set"
GENERATED_HEADER = "// Generated by anvil_kit.blocks.wood_set. Edits are overwritten on the next build.\n"

SCRIPTS = {
    "support": ("support", True, True),
    "togglable": ("togglable", True, False),
    "interactable": ("interactable", True, False),
    "door": ("door", True, False),
    "redstone_consumer": ("redstone-consumer", True, False),
    "strippable": ("strippable", True, True),
    "slab": ("slab", True, True),
    "sign": ("sign", True, False),
    "leaves": ("leaves", True, False),
    "sapling": ("sapling", True, False),
    "boat": ("boat", False, True),
}
"""Each script's module, and whether it registers a block component and world events."""

SERVER_UI_SCRIPTS = {"sign"}

_used: set[str] = set()


def constants_ts(namespace: str) -> str:
    """The `constants.ts` the scripts share: component ids, block states and helpers."""
    return _CONSTANTS_TS_HEAD + f'export const NAMESPACE = "{namespace}";\n' + _CONSTANTS_TS_TAIL


def script_ts(name: str) -> str:
    """The script of the `ns:wood_set_<name>` component (a key of `SCRIPTS`)."""
    return _SCRIPT_TS[SCRIPTS[name][0]]


def index_ts(used: Iterable[str]) -> str:
    """The `index.ts` whose `registerWoodSet(init)` registers the `used` scripts."""
    imports = []
    registrations = []
    events = []
    for name in used:
        module, has_component, has_events = SCRIPTS[name]
        title = "".join(word.capitalize() for word in module.split("-"))
        names = []
        if has_component:
            names.append(f"register{title}Component")
            registrations.append(f"\t{names[-1]}(init);\n")
        if has_events:
            names.append(f"register{title}Events")
            events.append(f"\t\t{names[-1]}();\n")
        imports.append(f'import {{ {", ".join(names)} }} from "./{module}";\n')

    return (
        'import { StartupEvent, world } from "@minecraft/server";\n'
        + "".join(imports)
        + "\n"
        + "// Single entry point: call once from `system.beforeEvents.startup`.\n"
        + "export function registerWoodSet(init: StartupEvent): void {\n"
        + "".join(registrations)
        + "\n"
        + "\t// World events can't be subscribed during startup, so they wait for world load.\n"
        + "\tworld.afterEvents.worldLoad.subscribe(() => {\n"
        + "".join(events)
        + "\t});\n"
        + "}\n"
    )


def write_typescript(created: Iterable[object]) -> None:
    """Write the scripts `created` use, and earlier wood sets used, into `OUTPUT_DIRECTORY`."""
    _used.update(_scripts_used_by(created))
    used = [name for name in SCRIPTS if name in _used]

    needs_ui = sorted(SERVER_UI_SCRIPTS & set(used))
    if needs_ui and not CONFIG._SCRIPT_UI:
        raise ValueError(
            f"The wood set scripts {needs_ui} use @minecraft/server-ui. "
            "Enable 'scriptui' in anvilconfig.json, or leave out WoodBlock.SIGN and WoodBlock.HANGING_SIGN."
        )

    output = Path(OUTPUT_DIRECTORY)
    output.mkdir(parents=True, exist_ok=True)
    _write(output / "constants.ts", constants_ts(CONFIG.NAMESPACE))
    for name in used:
        _write(output / f"{SCRIPTS[name][0]}.ts", script_ts(name))
    _write(output / "index.ts", index_ts(used))


def _scripts_used_by(created: Iterable[object]) -> set[str]:
    prefix = f"{CONFIG.NAMESPACE}:wood_set_"
    used = set()
    for block in created:
        if isinstance(block, Entity):
            used.add("boat")
        if not isinstance(block, Block):
            continue
        groups = [block.server.components, *block.server.permutations]
        for group in groups:
            for component in group:
                if component.identifier.startswith(prefix):
                    name = component.identifier.removeprefix(prefix)
                    if name not in SCRIPTS:
                        raise ValueError(
                            f"{block.identifier} uses `{component.identifier}`, which has no "
                            f"script. Add it to `SCRIPTS` in {Path(__file__).name}."
                        )
                    used.add(name)
    return used


def _write(path: Path, content: str) -> None:
    """Writes with CRLF, and leaves the file untouched when it already holds the same text."""
    data = (
        (GENERATED_HEADER + content)
        .replace("\r\n", "\n")
        .replace("\n", "\r\n")
        .encode("utf-8")
    )
    if path.is_file() and path.read_bytes() == data:
        return
    path.write_bytes(data)


