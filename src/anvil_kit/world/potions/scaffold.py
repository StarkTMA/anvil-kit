"""The potions' TypeScript. `index_ts()` is the `POTIONS` table of the registered potions plus
`registerPotions()`, `script_ts()` returns one of the runtime `SCRIPTS`, and `write_typescript()`
writes them all into the project on every `PotionAPI.register()` call, so the TypeScript can't
drift from the Python."""

import json
from collections.abc import Iterable
from pathlib import Path
from typing import TYPE_CHECKING

from anvil.lib.lib import AnvilFormatter

if TYPE_CHECKING:
    from .potion import Potion

__all__ = ["index_ts", "potion_name", "script_ts", "write_typescript"]

OUTPUT_DIRECTORY = "scripts/javascript/potions"
GENERATED_HEADER = "// Generated by anvil_kit.world.potions. Edits are overwritten on the next build.\n"

SCRIPTS = ("potion", "drinkable", "splash", "lingering")
"""The runtime modules written next to `index.ts`, each as `<name>.ts`."""


def script_ts(name: str) -> str:
    """The runtime module `name` (one of `SCRIPTS`). The namespace isn't written in: the
    scripts read it with `getNamespace()` from @starktma/minecraft-utils."""
    return _SCRIPT_TS[name]


def index_ts(potions: Iterable["Potion"]) -> str:
    """The `index.ts` with an exported `<effectKey>Potion` object per potion, and the `POTIONS`
    table of them keyed by `effect_id`."""
    potions = list(potions)
    objects = "".join(_potion_object(potion) for potion in potions)
    entries = "".join(
        f"\t{potion.effect_id}: {potion_name(potion)},\n" for potion in potions
    )
    return (
        _INDEX_TS_HEAD
        + objects
        + "export const POTIONS: Record<number, Potion> = {\n"
        + entries
        + "};\n"
        + _INDEX_TS_TAIL
    )


def potion_name(potion: "Potion") -> str:
    """The name `index.ts` exports `potion` under: `night_vision` is `nightVisionPotion`."""
    first, *rest = potion.key.split("_")
    return first + "".join(word.capitalize() for word in rest) + "Potion"


def _potion_object(potion: "Potion") -> str:
    return (
        f"export const {potion_name(potion)}: Potion = {{\n"
        f"\tid: {json.dumps(potion.key)},\n"
        f"\tcolor: {json.dumps(AnvilFormatter.convert_color(potion.color))},\n"
        f"\tamplifier: 0,\n"
        f"\tduration: 0,\n"
        f"}};\n\n"
    )


def write_typescript(potions: Iterable["Potion"]) -> None:
    """Write `index.ts` listing `potions`, and the `SCRIPTS`, into `OUTPUT_DIRECTORY`."""
    output = Path(OUTPUT_DIRECTORY)
    output.mkdir(parents=True, exist_ok=True)
    _write(output / "index.ts", index_ts(potions))
    for name in SCRIPTS:
        _write(output / f"{name}.ts", script_ts(name))


def _write(path: Path, content: str) -> None:
    """Writes with CRLF, and leaves the file untouched when it already holds the same text."""
    data = (
        (GENERATED_HEADER + content)
        .replace("\r\n", "\n")
        .replace("\n", "\r\n")
        .encode("utf-8")
    )
    if path.is_file() and path.read_bytes() == data:
        return
    path.write_bytes(data)


# region Texts


_INDEX_TS_HEAD = """\
import { StartupEvent, world } from "@minecraft/server";
import { registerDrinkable } from "./drinkable";
import { subscribeLingering } from "./lingering";
import { Potion } from "./potion";
import { subscribeSplash } from "./splash";

export type { Potion };

"""

_INDEX_TS_TAIL = """
export function registerPotions(init: StartupEvent): void {
\tregisterDrinkable(init);
\tworld.afterEvents.worldLoad.subscribe(() => {
\t\tsubscribeSplash(POTIONS);
\t\tsubscribeLingering(POTIONS);
\t});
}
"""

_POTION_TS = """\
import {
	Dimension,
	Entity,
	MolangVariableMap,
	RGBA,
	Vector3,
} from "@minecraft/server";
import { getNamespace } from "@starktma/minecraft-utils";
import { EffectObject } from "@starktma/minecraft-utils/minecraft";
import { hexToRgba } from "@starktma/minecraft-utils/math";

export interface Potion extends EffectObject {
	color: string;
}

export function thrownPotion(
	projectile: Entity,
	potions: Record<number, Potion>,
	type: number,
): Potion | undefined {
	const namespace = getNamespace();
	if (
		!projectile.isValid ||
		projectile.typeId !== `${namespace}:potion_projectile`
	)
		return;
	if (projectile.getProperty(`${namespace}:type`) !== type) return;

	const potion =
		potions[projectile.getProperty(`${namespace}:effect_id`) as number];
	if (!potion) return;
	return {
		...potion,
		amplifier: projectile.getProperty(`${namespace}:amplifier`) as number,
		duration: (projectile.getProperty(`${namespace}:duration`) as number) * 20,
	};
}

export function spawnParticle(
	dimension: Dimension,
	particle: string,
	location: Vector3,
	color: string,
	floats: Record<string, number>,
): void {
	const variables = new MolangVariableMap();
	variables.setColorRGBA("color", hexToRgba(color) as RGBA);
	for (const [name, value] of Object.entries(floats))
		variables.setFloat(name, value);
	dimension.spawnParticle(particle, location, variables);
}
"""

_DRINKABLE_TS = """\
import {
	CustomComponentParameters,
	ItemComponentConsumeEvent,
	ItemCustomComponent,
	StartupEvent,
} from "@minecraft/server";
import { getNamespace } from "@starktma/minecraft-utils";
import { effectManager } from "@starktma/minecraft-utils/minecraft";

interface DrinkableParameters {
	effect: string;
	amplifier: number;
	duration: number;
}

function onConsume(
	event: ItemComponentConsumeEvent,
	{ params }: CustomComponentParameters,
): void {
	const { effect, amplifier, duration } = params as DrinkableParameters;
	effectManager.addEffect(event.source, effect, amplifier, duration * 20);
}

const drinkableComponent: ItemCustomComponent = { onConsume };

export function registerDrinkable(init: StartupEvent): void {
	init.itemComponentRegistry.registerCustomComponent(
		`${getNamespace()}:potion_effect`,
		drinkableComponent,
	);
}
"""


_SPLASH_TS = """\
import { Dimension, Entity, Vector3, world } from "@minecraft/server";
import { getNamespace } from "@starktma/minecraft-utils";
import { effectManager } from "@starktma/minecraft-utils/minecraft";
import { Potion, spawnParticle, thrownPotion } from "./potion";

const SPLASH = 1;

export function subscribeSplash(potions: Record<number, Potion>): void {
	world.afterEvents.projectileHitBlock.subscribe((event) =>
		onSplashHit(event.projectile, potions),
	);
	world.afterEvents.projectileHitEntity.subscribe((event) =>
		onSplashHit(event.projectile, potions),
	);
}

function onSplashHit(
	projectile: Entity,
	potions: Record<number, Potion>,
): void {
	const potion = thrownPotion(projectile, potions, SPLASH);
	if (!potion) return;

	const { dimension } = projectile;
	const location = { ...projectile.location, y: projectile.location.y + 0.1 };
	const range = projectile.getProperty(
		`${getNamespace()}:splash_range`,
	) as number;
	projectile.remove();
	splash(dimension, location, potion, range);
}

export function splash(
	dimension: Dimension,
	location: Vector3,
	potion: Potion,
	range: number,
): void {
	spawnParticle(
		dimension,
		"minecraft:splash_spell_emitter",
		location,
		potion.color,
		{
			splash_range: range,
			splash_power: 1,
		},
	);
	for (const entity of dimension.getEntities({
		location,
		maxDistance: range,
	})) {
		effectManager.addEffect(
			entity,
			potion.id,
			potion.amplifier,
			potion.duration,
		);
	}
}
"""

_LINGERING_TS = """\
import { Dimension, Entity, system, Vector3, world } from "@minecraft/server";
import { getNamespace } from "@starktma/minecraft-utils";
import { effectManager } from "@starktma/minecraft-utils/minecraft";
import { Potion, spawnParticle, thrownPotion } from "./potion";

interface Cloud extends Potion {
	dimension: Dimension;
	location: Vector3;
	startRadius: number;
	radius: number;
	lifetime: number;
	age: number;
	affected: Set<string>;
}

const LINGERING = 2;

const clouds = new Set<Cloud>();

export function subscribeLingering(potions: Record<number, Potion>): void {
	world.afterEvents.projectileHitBlock.subscribe((event) =>
		addCloud(event.projectile, potions),
	);
	world.afterEvents.projectileHitEntity.subscribe((event) =>
		addCloud(event.projectile, potions),
	);
	system.runInterval(tickClouds, 1);
}

function addCloud(projectile: Entity, potions: Record<number, Potion>): void {
	const potion = thrownPotion(projectile, potions, LINGERING);
	if (!potion) return;

	const namespace = getNamespace();
	const radius = projectile.getProperty(
		`${namespace}:lingering_radius`,
	) as number;
	clouds.add({
		...potion,
		dimension: projectile.dimension,
		location: { ...projectile.location, y: projectile.location.y + 0.1 },
		startRadius: radius,
		radius,
		lifetime: projectile.getProperty(
			`${namespace}:lingering_lifetime`,
		) as number,
		age: 0,
		affected: new Set(),
	});
	projectile.remove();
}

function tickClouds(): void {
	for (const cloud of clouds) {
		cloud.age++;
		const radius = cloud.radius * (1 - cloud.age / cloud.lifetime);
		if (radius <= 0 || !cloud.dimension.isChunkLoaded(cloud.location)) {
			clouds.delete(cloud);
			continue;
		}

		spawnParticle(
			cloud.dimension,
			"minecraft:mobspell_lingering",
			cloud.location,
			cloud.color,
			{
				cloud_lifetime: cloud.lifetime / 20,
				cloud_radius: radius,
				particle_multiplier: radius / cloud.startRadius,
			},
		);
		if (cloud.age < 20) continue;

		for (const entity of cloud.dimension.getEntities({
			location: cloud.location,
			maxDistance: radius + 1,
		})) {
			if (cloud.affected.has(entity.id)) continue;
			effectManager.addEffect(
				entity,
				cloud.id,
				cloud.amplifier,
				cloud.duration,
			);
			cloud.radius = Math.max(0, cloud.radius - 0.5);
			cloud.lifetime = Math.max(1, cloud.lifetime - 100);
			cloud.affected.add(entity.id);
			system.runTimeout(() => cloud.affected.delete(entity.id), 60);
		}
	}
}
"""

_SCRIPT_TS = {
    "potion": _POTION_TS,
    "drinkable": _DRINKABLE_TS,
    "splash": _SPLASH_TS,
    "lingering": _LINGERING_TS,
}


