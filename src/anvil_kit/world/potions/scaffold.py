"""The potions' TypeScript. `potions_ts()` is the runtime that drinks, splashes and lingers,
`index_ts()` is the `POTIONS` table of the registered potions plus `registerPotions()`, and
`write_typescript()` writes both into the project on every `PotionAPI.register()` call, so the
TypeScript can't drift from the Python."""

import json
from collections.abc import Iterable
from pathlib import Path
from typing import TYPE_CHECKING

from anvil.lib.lib import AnvilFormatter

if TYPE_CHECKING:
    from .config import PotionConfig

__all__ = ["index_ts", "potions_ts", "write_typescript"]

OUTPUT_DIRECTORY = "scripts/javascript/potions"
GENERATED_HEADER = "// Generated by anvil_kit.world.potions. Edits are overwritten on the next build.\n"


def potions_ts() -> str:
    """The `potions.ts` runtime. The namespace isn't written in: it reads it with
    `getNamespace()` from @starktma/minecraft-utils."""
    return _POTIONS_TS


def index_ts(configs: Iterable["PotionConfig"]) -> str:
    """The `index.ts` with a `POTIONS` entry per config, keyed by `effect_id`."""
    entries = "".join(_entry(config) for config in configs)
    return (
        _INDEX_TS_HEAD
        + "export const POTIONS = {\n"
        + entries
        + "} as const;\n"
        + _INDEX_TS_TAIL
    )


def _entry(config: "PotionConfig") -> str:
    return (
        f"\t{config.effect_id}: {{\n"
        f"\t\tid: {json.dumps(config.effect_key)},\n"
        f"\t\tcolor: {json.dumps(AnvilFormatter.convert_color(config.color_hex))},\n"
        f"\t\tamplifier: 0,\n"
        f"\t\tduration: 0,\n"
        f"\t\tsplashRange: {str(int(round(float(config.splash_range), 4)))},\n"
        f"\t\tlingeringRadius: {str(int(round(float(config.lingering_radius), 4)))},\n"
        f"\t\tlingeringLifetime: {str(round(config.lingering_lifetime * 20))},\n"
        f"\t}},\n"
    )


def write_typescript(configs: Iterable["PotionConfig"]) -> None:
    """Write `potions.ts` and an `index.ts` listing `configs` into `OUTPUT_DIRECTORY`."""
    output = Path(OUTPUT_DIRECTORY)
    output.mkdir(parents=True, exist_ok=True)
    _write(output / "potions.ts", potions_ts())
    _write(output / "index.ts", index_ts(configs))


def _write(path: Path, content: str) -> None:
    """Writes with CRLF, and leaves the file untouched when it already holds the same text."""
    data = (
        (GENERATED_HEADER + content)
        .replace("\r\n", "\n")
        .replace("\n", "\r\n")
        .encode("utf-8")
    )
    if path.is_file() and path.read_bytes() == data:
        return
    path.write_bytes(data)


