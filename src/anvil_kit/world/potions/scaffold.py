_INDEX_TS_HEAD = """\
import { StartupEvent } from "@minecraft/server";
import { startPotions } from "./potions";

export type { Potion } from "./potions";

"""

_INDEX_TS_TAIL = """
export function registerPotions(init: StartupEvent): void {
\tstartPotions(init, POTIONS);
}
"""

_POTIONS_TS = """\
import {
	Dimension,
	Entity,
	MolangVariableMap,
	RGBA,
	StartupEvent,
	system,
	Vector3,
	world,
} from "@minecraft/server";
import { getNamespace } from "@starktma/minecraft-utils";
import { effectManager, EffectObject } from "@starktma/minecraft-utils/minecraft";
import { hexToRgba } from "@starktma/minecraft-utils/math";

export interface Potion extends EffectObject {
	color: string;
	splashRange: number;
	lingeringRadius: number;
	lingeringLifetime: number;
}

interface Cloud extends Potion {
	dimension: Dimension;
	location: Vector3;
	radius: number;
	age: number;
	affected: Set<string>;
}

const SPLASH = 1;
const LINGERING = 2;

let potions: Record<number, Potion> = {};
const clouds = new Set<Cloud>();

export function startPotions(init: StartupEvent, table: Record<number, Potion>): void {
	potions = table;
	for (const potion of Object.values(table)) registerDrinkable(init, potion);
	world.afterEvents.worldLoad.subscribe(subscribeEvents);
}

function registerDrinkable(init: StartupEvent, potion: Potion): void {
	init.itemComponentRegistry.registerCustomComponent(
		`${getNamespace()}:${potion.id}_potion_effect`,
		{
			onConsume: (event, { params }) => {
				const { amplifier, duration } = params as Potion;
				applyPotion(event.source, withStrength(potion, amplifier, duration));
			},
		},
	);
}

function subscribeEvents(): void {
	world.afterEvents.projectileHitBlock.subscribe((event) =>
		onProjectileHit(event.projectile),
	);
	world.afterEvents.projectileHitEntity.subscribe((event) =>
		onProjectileHit(event.projectile),
	);
	system.runInterval(tickClouds, 1);
}

function onProjectileHit(projectile: Entity): void {
	if (
		!projectile.isValid ||
		projectile.typeId !== `${getNamespace()}:potion_projectile`
	)
		return;

	const definition = potions[getProperty(projectile, "effect_id")];
	if (definition) {
		const potion = withStrength(
			definition,
			getProperty(projectile, "amplifier"),
			getProperty(projectile, "duration"),
		);
		const type = getProperty(projectile, "type");
		if (type === SPLASH) splash(projectile, potion);
		if (type === LINGERING) addCloud(projectile, potion);
	}
	projectile.remove();
}

function splash(projectile: Entity, potion: Potion): void {
	const location = landingLocation(projectile);
	spawnParticle(
		projectile.dimension,
		"minecraft:splash_spell_emitter",
		location,
		potion.color,
		{
			splash_range: potion.splashRange,
			splash_power: 1,
		},
	);
	for (const entity of getNearbyEntities(
		projectile.dimension,
		location,
		potion.splashRange,
	)) {
		if (entity.id !== projectile.id) applyPotion(entity, potion);
	}
}

function addCloud(projectile: Entity, potion: Potion): void {
	clouds.add({
		...potion,
		dimension: projectile.dimension,
		location: landingLocation(projectile),
		radius: potion.lingeringRadius,
		age: 0,
		affected: new Set(),
	});
}

function tickClouds(): void {
	for (const cloud of clouds) tickCloud(cloud);
}

function tickCloud(cloud: Cloud): void {
	cloud.age++;
	const radius = cloud.radius * (1 - cloud.age / cloud.lingeringLifetime);
	if (radius <= 0 || !cloud.dimension.isChunkLoaded(cloud.location)) {
		clouds.delete(cloud);
		return;
	}

	spawnParticle(
		cloud.dimension,
		"minecraft:mobspell_lingering",
		cloud.location,
		cloud.color,
		{
			cloud_lifetime: cloud.lingeringLifetime / 20,
			cloud_radius: radius,
			particle_multiplier: radius / cloud.lingeringRadius,
		},
	);
	if (cloud.age < 20) return;

	for (const entity of getNearbyEntities(
		cloud.dimension,
		cloud.location,
		radius + 1,
	)) {
		if (!cloud.affected.has(entity.id)) touchCloud(cloud, entity);
	}
}

function touchCloud(cloud: Cloud, entity: Entity): void {
	applyPotion(entity, cloud);
	cloud.radius = Math.max(0, cloud.radius - 0.5);
	cloud.lingeringLifetime = Math.max(1, cloud.lingeringLifetime - 100);
	cloud.affected.add(entity.id);
	system.runTimeout(() => cloud.affected.delete(entity.id), 60);
}

function withStrength(potion: Potion, amplifier: number, seconds: number): Potion {
	return { ...potion, amplifier, duration: seconds * 20 };
}

function applyPotion(entity: Entity, potion: Potion): void {
	effectManager.addEffect(entity, potion.id, potion.amplifier, potion.duration);
}

function getProperty(entity: Entity, name: string): number {
	return entity.getProperty(`${getNamespace()}:${name}`) as number;
}

function landingLocation(projectile: Entity): Vector3 {
	return { ...projectile.location, y: projectile.location.y + 0.1 };
}

function getNearbyEntities(
	dimension: Dimension,
	location: Vector3,
	maxDistance: number,
): Entity[] {
	return dimension.getEntities({
		location,
		maxDistance,
	});
}

function spawnParticle(
	dimension: Dimension,
	particle: string,
	location: Vector3,
	color: string,
	floats: Record<string, number>,
): void {
	const variables = new MolangVariableMap();
	variables.setColorRGBA("color", hexToRgba(color) as RGBA);
	for (const [name, value] of Object.entries(floats)) variables.setFloat(name, value);
	dimension.spawnParticle(particle, location, variables);
}
"""


